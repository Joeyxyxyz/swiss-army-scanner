"""
QUICK CHECK mode: a triangulation preset + ONE simple check -> CONTINUE / REJECT / PULL.

No sensors, no permissions, no station configuration to write. It is not a second engine:
build_config() makes the minimal SINGLE-JOB station config for the check and the station job
runner runs it (`scan run`'s own code path, ui/cli.py; engine/flow/schema.lift_legacy reads a
single job as a one-step flow with no sensor claim and no permission). So the verdict, the
disposition, the guard band, result.json (the run schema of engine/runs.py) and the exit
codes are exactly a station run's:

    flatness   job.type metric, measure plane: the robust max |deviation| from the plane
               fitted in the roi vs threshold_mm (out-of-tolerance clusters FAIL)
    golden     job.type metric, measure golden: every foreground component vs a golden
               metric scan, both directions, vs threshold_mm
    recipe     job.type recipe: one recipe (its own zones, tolerances and guard band)

    exit 0 CONTINUE, 1 REJECT, 5 PULL (2 refused, 4 crashed: PULL in result.json)

The generated config is written into the run folder (quick_check.json: `scan run` on it
runs the same check again) and marked "operating_mode": "quick_check"; so is the run's
result.json. Quick check asks the rig gate strictly (engine/rigstate.py): a mobile rig not
verified in this session (`rig_unverified`), or a fixed rig whose rig check said MOVED /
UNKNOWN and was not answered since (`rig_check`), is a PULL.

Pure: it only builds the document.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Optional

from .. import disposition as D

MODE = "quick_check"
CHECKS = ("flatness", "golden", "recipe")
STATION_ID = "quick_check"
CONFIG_FILE = "quick_check.json"        # the generated config, kept in the run folder
SCANS = ("fast", "metric")


def _num(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


def build_config(check: str, preset: Optional[str] = None, *, threshold_mm=None, roi=None,
                 golden: Optional[str] = None, recipe: Optional[str] = None,
                 guard_band_pct: float = 0.0, runs_dir=None, zone: Optional[str] = None,
                 scan: str = "fast", station_id: str = STATION_ID,
                 mock_part: Optional[str] = None) -> dict:
    """The minimal single-job station config of one quick check (ui/run_job reads it as any
    station config). ValueError lists every problem.

    check flatness: threshold_mm (the flatness limit: max |deviation| from the plane, mm),
    optional roi [x0, y0, x1, y1] camera px. check golden: threshold_mm + golden (the id or
    label of a golden metric scan; never `latest`), optional roi. check recipe: recipe (a
    recipe name or file); its tolerances and guard band are the recipe's own, so
    threshold_mm / roi / golden / guard_band_pct are refused. preset: the triangulation
    preset (required for flatness / golden; a recipe pins its own, and a preset named here
    wins over it). zone (flatness / golden): what is lit - grid cells, painted zone sets
    ("zoneset:<set>[:Z1,Z3]", several as "zoneset:<a>+<b>") or "selection" (the zone sets
    switched on at this rig placement; "selection@<stamp>" = exactly the selection that was
    shown). Painted zones are judged ONE BY ONE by the job runner: the limit applies to each
    zone, and a zone that cannot be judged is a PULL (ui/cli.py _run_metric_zones)."""
    bad = []
    if check not in CHECKS:
        raise ValueError(f"quick check: check {check!r} is not one of {', '.join(CHECKS)}")
    if preset is not None and (not isinstance(preset, str) or not preset.strip()):
        bad.append("preset must be a preset name")
    if scan not in SCANS:
        bad.append(f"scan must be one of {', '.join(SCANS)}")
    try:
        gb = D.check_pct(0.0 if guard_band_pct is None else guard_band_pct)
    except ValueError as e:
        bad.append(str(e))
        gb = 0.0
    if roi is not None and (not isinstance(roi, (list, tuple)) or len(roi) != 4 or not all(
            isinstance(v, int) and not isinstance(v, bool) and v >= 0 for v in roi)
            or roi[2] <= roi[0] or roi[3] <= roi[1]):
        bad.append("roi must be [x0, y0, x1, y1] camera px (whole numbers >= 0, x1 > x0, "
                   "y1 > y0)")
    doc = {"_comment": "Quick check (generated by `scan quick-check`): a triangulation preset + "
                       "ONE check, no sensors, no permissions. `scan run <this file>` runs it "
                       "again.",
           "operating_mode": MODE, "station_id": str(station_id),
           "preset": preset.strip() if isinstance(preset, str) and preset.strip() else None,
           "library": None, "mock_library": None,
           "runs_dir": str(Path(runs_dir)) if runs_dir else None,
           "operator_confirmed": False}
    if mock_part:
        doc["mock_part"] = str(mock_part)
    if check == "recipe":
        if not isinstance(recipe, str) or not recipe.strip():
            bad.append("check recipe needs recipe: a recipe name (`scan recipe-list`) or file")
        for k, v in (("threshold_mm", threshold_mm), ("roi", roi), ("golden", golden),
                     ("zone", zone)):
            if v is not None:
                bad.append(f"{k} is not for a recipe check: the recipe has its own zones, "
                           "tolerances and guard band")
        if gb:
            bad.append("guard_band_pct is not for a recipe check: the recipe sets its own "
                       "(pull.guard_band_pct)")
        doc.update(threshold_mm=None, require_mm=True,
                   job={"type": "recipe", "recipe": recipe.strip() if isinstance(recipe, str)
                        else None},
                   part={"role": "test", "label": "quick_check"})
    else:
        if not doc["preset"]:
            bad.append(f"check {check} needs a triangulation preset")
        if not _num(threshold_mm) or threshold_mm <= 0:
            bad.append("threshold_mm must be a positive, finite number (mm): "
                       + ("the flatness limit" if check == "flatness" else
                          "the largest deviation from the golden allowed"))
        if recipe is not None:
            bad.append("recipe is for check recipe")
        if check == "golden":
            if not isinstance(golden, str) or not golden.strip():
                bad.append("check golden needs golden: the id or label of a golden metric scan "
                           "(a GOOD part scanned once)")
        elif golden is not None:
            bad.append("golden is for check golden")
        doc.update(threshold_mm=float(threshold_mm) if _num(threshold_mm) else None,
                   job={"type": "metric", "scan": scan, "axis": "xy", "zone": zone or None,
                        "measure": "plane" if check == "flatness" else "golden",
                        "roi": [int(v) for v in roi] if roi is not None and not bad else None,
                        "golden": golden.strip() if isinstance(golden, str) and golden.strip()
                        else None, "guard_band_pct": gb},
                   part={"role": "test", "label": "quick_check"})
    if bad:
        raise ValueError(f"quick check: {len(bad)} problem(s): " + "; ".join(bad))
    return doc
